export const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  es,
  pt,
};

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

/**
 * Traduce una clave. Acepta parametros con la forma {nombre}.
 * Si falta la traduccion usa el español y, en ultima instancia, la clave.
 */
export function translate(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const table = dictionaries[locale] ?? dictionaries[DEFAULT_LOCALE];
  let text: string = table[key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value));
    }
  }
  return text;
}
